import { readFileSync, writeFileSync } from "node:fs";
import { generateOperations } from "../src/generator.js";

const spec = JSON.parse(readFileSync(new URL("../spec/etsy-openapi.json", import.meta.url), "utf8"));
const ops = generateOperations(spec);
const body =
  `// Generated by \`npm run gen:local\` from spec/etsy-openapi.json. Do not edit.\n` +
  `import type { OperationDescriptor } from "../operation.js";\n\n` +
  `export const operations: OperationDescriptor[] = ${JSON.stringify(ops, null, 2)};\n`;
writeFileSync(new URL("../src/generated/operations.ts", import.meta.url), body);
console.log(`Generated ${ops.length} operations`);
